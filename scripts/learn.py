#!/usr/bin/env python3
"""Record a lesson without inflating a skill.

The desk's case law used to be written by appending a paragraph to `skills/evergreen_topics.md`
(245 KB at its peak, +2–4 KB per run). That file is read into an agent's context on every run, so
each append was re-billed on every future run, forever: a write-back loop with no ceiling.

Lessons now land here instead, dated and structured:

    # a probe result — goes into the host ledger, so `host_probe --check` answers with it
    python3 scripts/learn.py --vertical resilient_home_assets --kind host \
        --url https://example.gov/vent-codes --verdict unreachable --note "403 to the verifier"

    # a pitfall / house rule — one per file, dated, keyed by vertical
    python3 scripts/learn.py --vertical resilient_home_assets --kind pitfall --file /tmp/lesson.md

    python3 scripts/learn.py --digest        # regenerate context/knowledge/DIGEST.md

Nothing here is read by a pipeline run unless someone asks for it: `skills/references/*_casebook.md`
and `DIGEST.md` are for the moment you hit the same wall, not for the prefix of every call.
"""
from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
KNOW = ROOT / "context" / "knowledge"
HOSTS = KNOW / "host_probes.json"
VERDICTS = ("fetchable", "unreachable", "no_figures", "partial", "mentioned")


def _today() -> str:
    return datetime.date.today().isoformat()


def record_host(vertical: str, url: str, verdict: str, note: str) -> dict:
    if verdict not in VERDICTS:
        raise SystemExit(f"verdict must be one of {', '.join(VERDICTS)}")
    host = re.sub(r"^https?://", "", url.strip()).split("/")[0].lower()
    if "." not in host:
        raise SystemExit(f"not a host: {url!r}")
    rows = []
    if HOSTS.exists():
        try:
            rows = json.loads(HOSTS.read_text(encoding="utf-8"))
        except ValueError:
            rows = []
    row = {"host": host, "url": url.strip(), "verdict": verdict, "as_of": _today(),
           "vertical": vertical, "note": note.strip()[:220]}
    # one row per (host, verdict) per day: re-running the same lesson does not grow the file
    rows = [r for r in rows if not (r.get("host") == host and r.get("verdict") == verdict
                                    and r.get("as_of") == row["as_of"])]
    rows.append(row)
    rows.sort(key=lambda r: (r.get("host", ""), r.get("verdict", "")))
    HOSTS.parent.mkdir(parents=True, exist_ok=True)
    HOSTS.write_text(json.dumps(rows, indent=1) + "\n", encoding="utf-8")
    return row


def record_note(vertical: str, kind: str, text: str) -> dict:
    text = text.strip()
    if len(text) < 20:
        raise SystemExit("a lesson under 20 chars is not a lesson")
    row = {"as_of": _today(), "vertical": vertical, "kind": kind, "text": text,
           "chars": len(text)}
    path = KNOW / f"{vertical}.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(row) + "\n")
    return row


def digest() -> pathlib.Path:
    """One markdown file with every lesson, newest first — the thing a human or a model reads
    when it hits the wall the lesson is about."""
    out = [ "# Learned at the desk", "",
            "Generated by `scripts/learn.py --digest` from `context/knowledge/*.jsonl` and",
            "`context/knowledge/host_probes.json`. Not part of any run's context: read the section",
            "you need.", "" ]
    lessons: list[dict] = []
    for path in sorted(KNOW.glob("*.jsonl")):
        for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                lessons.append(json.loads(line))
            except ValueError:
                continue
    lessons.sort(key=lambda r: (r.get("as_of", ""), r.get("vertical", "")), reverse=True)
    for row in lessons:
        out += [f"## {row.get('as_of','')} · {row.get('vertical','')} · {row.get('kind','')}", "",
                row.get("text", "").strip(), ""]
    if HOSTS.exists():
        rows = json.loads(HOSTS.read_text(encoding="utf-8"))
        out += ["## Host ledger", "",
                "| host | verdict | as of | vertical | note |", "|---|---|---|---|---|"]
        for r in sorted(rows, key=lambda r: (r.get("verdict", ""), r.get("host", ""))):
            note = (r.get("note") or "").replace("|", "/")[:120]
            out.append(f"| {r.get('host','')} | {r.get('verdict','')} | {r.get('as_of','')} | "
                       f"{r.get('vertical','')} | {note} |")
        out.append("")
    path = KNOW / "DIGEST.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return path


def selftest() -> int:
    problems = []
    if HOSTS.exists():
        try:
            rows = json.loads(HOSTS.read_text(encoding="utf-8"))
        except ValueError as exc:
            problems.append(f"host_probes.json does not parse: {exc}")
            rows = []
        bad = [r for r in rows if r.get("verdict") not in VERDICTS]
        if bad:
            problems.append(f"{len(bad)} host row(s) with an unknown verdict")
    else:
        problems.append("host_probes.json is missing (run scripts/host_probe.py --rebuild)")
    if problems:
        for p in problems:
            print(f"FAIL: {p}")
        return 1
    print("ok: knowledge store parses")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Record a lesson without growing a skill")
    ap.add_argument("--vertical", default="")
    ap.add_argument("--kind", default="pitfall", choices=("pitfall", "rule", "host"))
    ap.add_argument("--file", default="", help="markdown file holding the lesson ('-' for stdin)")
    ap.add_argument("--text", default="", help="the lesson inline")
    ap.add_argument("--url", default="")
    ap.add_argument("--verdict", default="")
    ap.add_argument("--note", default="")
    ap.add_argument("--digest", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()

    if args.digest:
        print(f"wrote {digest().relative_to(ROOT)}")
        return 0
    if args.selftest:
        return selftest()

    if args.kind == "host":
        if not (args.vertical and args.url and args.verdict):
            raise SystemExit("--kind host needs --vertical --url --verdict [--note]")
        row = record_host(args.vertical, args.url, args.verdict, args.note)
        print(f"host ledger: {row['host']} → {row['verdict']} ({row['as_of']})")
        return 0

    if not args.vertical:
        raise SystemExit("--vertical is required")
    if args.file:
        text = sys.stdin.read() if args.file == "-" else pathlib.Path(args.file).read_text(
            encoding="utf-8", errors="ignore")
    else:
        text = args.text
    if not text.strip():
        raise SystemExit("nothing to record: pass --file or --text")
    row = record_note(args.vertical, args.kind, text)
    print(f"recorded {row['kind']} for {row['vertical']} ({row['chars']} chars, {row['as_of']}); "
          f"run `scripts/learn.py --digest` to fold it into DIGEST.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
